FSE15_CIRCUIT_TEXT = """[Schéma textuel original, rédigé pour ce cours]

QUATRE AGENTS DU CIRCUIT ÉCONOMIQUE

MÉNAGES — fournissent leur travail aux entreprises et reçoivent un salaire en échange. \
Utilisent leur revenu pour consommer des biens/services et payer des impôts/cotisations.

ENTREPRISES — produisent des biens et services, versent des salaires aux ménages qui y \
travaillent, vendent leur production (consommation des ménages, investissements, \
exportations), et paient des impôts/cotisations.

ÉTAT — perçoit des impôts et des cotisations (ménages et entreprises), et effectue des \
dépenses : services publics (utilisés par les ménages et les entreprises) et prestations \
sociales (versées aux ménages, ex. allocations, pensions).

RESTE DU MONDE — achète des biens/services produits par les entreprises du pays \
(exportations) et vend des biens/services aux agents du pays (importations).

FLUX À COMPLÉTER DANS UN EXERCICE (exemples de flux réels et monétaires entre agents) :
- Ménages → Entreprises : travail (flux réel) / Entreprises → Ménages : salaires (flux \
monétaire).
- Ménages → Entreprises : achats de biens/services, consommation (flux monétaire et réel \
combinés).
- Ménages/Entreprises → État : impôts et cotisations (flux monétaire).
- État → Ménages : prestations sociales (flux monétaire) ; État → Ménages/Entreprises : \
services publics (flux réel).
- Entreprises → Reste du monde : exportations (flux réel) / Reste du monde → Entreprises : \
paiement des exportations (flux monétaire).
- Reste du monde → Ménages/Entreprises : importations (flux réel) / Ménages/Entreprises → \
Reste du monde : paiement des importations (flux monétaire)."""

