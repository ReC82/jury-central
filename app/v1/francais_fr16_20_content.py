FR17_STORY_TITLE = "Nouvelle — Le dernier bus"
FR17_STORY_TEXT = """Ce soir de novembre, la pluie tombait sur Charleroi depuis des \
heures. Maëlle, seize ans, sortait de son entraînement de basket, son sac trempé sur \
l'épaule. Comme tous les mardis, elle comptait prendre le bus de 21 h 40, le dernier de \
la ligne 52.

Quand elle arriva à l'arrêt, elle vit les feux rouges du bus disparaître au bout de \
l'avenue. Elle avait trois minutes de retard. Son téléphone affichait 2 % de batterie ; \
il s'éteignit avant qu'elle ait pu appeler sa mère.

Maëlle resta d'abord immobile, la gorge serrée. Puis elle se mit à marcher. Six \
kilomètres la séparaient de chez elle, et la route longeait des entrepôts déserts. Au \
bout d'un quart d'heure, une camionnette blanche ralentit à sa hauteur. Son cœur se mit \
à battre très fort. La vitre descendit : c'était Monsieur Ferreira, le vieux boulanger de \
son quartier, qui rentrait de livrer un restaurant.

« Maëlle ? Qu'est-ce que tu fais là, sous la pluie ? »

Elle hésita. Sa mère lui avait toujours dit de ne jamais monter dans la voiture de \
quelqu'un. Mais elle connaissait Monsieur Ferreira depuis qu'elle était petite : chaque \
dimanche, il lui donnait un croissant en plus. Elle lui demanda seulement de téléphoner \
à sa mère avec son portable à lui. Sa mère décrocha tout de suite, folle d'inquiétude, \
et donna son accord.

Pendant le trajet, Monsieur Ferreira raconta qu'à son âge, il avait lui aussi raté un \
dernier train, à Porto, et qu'il avait dormi sur un banc de la gare. Maëlle rit pour la \
première fois de la soirée.

Devant l'immeuble, sa mère l'attendait sous un parapluie. Elle serra Maëlle dans ses bras, \
puis serra la main du boulanger en le remerciant longuement. Le dimanche suivant, c'est \
Maëlle qui apporta à la boulangerie une boîte de biscuits qu'elle avait faits elle-même. \
Et depuis ce soir-là, elle ne sort plus jamais sans une batterie de secours dans son sac."""

