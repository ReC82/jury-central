FSE14_ISSUES_TEXT = """[Document original, rédigé pour ce cours à partir de constats généraux publics \
et datés — aucun chiffre réel]

Deux évolutions générales pèsent sur le financement de la sécurité sociale, de façon \
documentée et régulièrement commentée par les institutions publiques belges :

1. Le VIEILLISSEMENT DE LA POPULATION : un nombre croissant de personnes atteint l'âge de \
la retraite par rapport au nombre de personnes en activité qui cotisent, ce qui augmente les \
dépenses de pension tout en maintenant un nombre de cotisants relativement plus restreint.

2. L'AUGMENTATION DES DÉPENSES DE SANTÉ : les progrès médicaux et le vieillissement de la \
population augmentent le coût global des soins remboursés par l'assurance maladie- \
invalidité, ce qui pèse sur le financement de cette branche.

Ces deux évolutions sont des enjeux généraux, documentés par les institutions publiques \
belges, sans qu'un montant ou une projection chiffrée précise soit donné ici."""
